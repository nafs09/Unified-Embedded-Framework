#!/usr/bin/env python3
"""Create inert standalone-template scope files for every UETD module.

The module registry and its detail manifests identify the current catalog.
Public headers and implementation sources are recorded in each generated
template as the resources a future route must use. These files contain only
comments and are deliberately not listed in any renderable template_paths
field. They are a planning inventory, not a code-generation implementation.
"""

from __future__ import annotations
import json
import re
from pathlib import Path, PurePosixPath, PureWindowsPath
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "registry" / "modules" / "registry.json"
OUTPUT_ROOT = ROOT / "templates" / "modules"
INDEX = OUTPUT_ROOT / "index.json"
CATALOG = OUTPUT_ROOT / "catalog.md"
GENERATOR_ID = "tools/generate_module_template_scaffolds.py"
GENERATED_MARKER = "Generated by " + GENERATOR_ID + "."
MODULE_ID = re.compile(r"^[A-Za-z0-9_/-]+$")

def _read_json(path: Path) -> dict[str, Any]:
    document = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(document, dict):
        raise ValueError(f"expected a JSON object in {path.relative_to(ROOT)}")
    return document

def _safe_relative(value: object, label: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{label} must be a non-empty relative path")
    normalized = value.replace("\\", "/")
    path = PurePosixPath(normalized)
    windows_path = PureWindowsPath(normalized)
    if path.is_absolute() or windows_path.is_absolute() or windows_path.drive or ".." in path.parts or not path.parts:
        raise ValueError(f"unsafe {label}: {value!r}")
    return path.as_posix()

def _resource_paths(record: dict[str, Any], field: str) -> list[str]:
    raw = record.get(field, [])
    if not isinstance(raw, list):
        raise ValueError(f"module manifest {field!r} must be an array")
    return [_safe_relative(item, f"module {field} path") for item in raw]

def _is_future(module_id: str, record: dict[str, Any], resources: list[str]) -> bool:
    segments = module_id.split("/")
    return "future" in segments or record.get("scaffold_stage") == "future" or any("future" in PurePosixPath(resource).parts for resource in resources)

def _output_relative_path(module_id: str, future: bool) -> Path:
    if not MODULE_ID.fullmatch(module_id):
        raise ValueError(f"invalid module ID: {module_id!r}")
    parts = list(PurePosixPath(module_id).parts)
    if future and len(parts) > 1 and "future" not in parts:
        parts.insert(1, "future")
    return Path(*parts, "route.tmpl")

def _comment(value: object) -> str:
    return str(value).replace("*/", "* /").replace("\r", " ").replace("\n", " ").strip()

def _comment_list(items: list[str]) -> list[str]:
    return [" *   - " + item for item in items] if items else [" *   - (none declared)"]

def _resource_exists(path: str) -> bool:
    resolved = (ROOT / Path(*PurePosixPath(path).parts)).resolve()
    try:
        resolved.relative_to(ROOT.resolve())
    except ValueError as exc:
        raise ValueError(f"resource path escapes UETD root: {path!r}") from exc
    return resolved.is_file()

def _api_symbols(record: dict[str, Any], headers: list[str]) -> list[str]:
    outlined = record.get("outlined_functions")
    if isinstance(outlined, list) and outlined:
        return sorted({_comment(item) for item in outlined if isinstance(item, str)})
    authoring = record.get("authoring")
    if isinstance(authoring, dict):
        symbols: set[str] = set()
        operations = authoring.get("operations", [])
        if not isinstance(operations, list):
            operations = []
        for operation in operations:
            if isinstance(operation, dict) and isinstance(operation.get("symbol"), str):
                symbols.add(_comment(operation["symbol"]))
        if symbols:
            return sorted(symbols)
    # Public header names are the source of truth. The prefix filter excludes
    # C keywords and most type/macro expressions while retaining UETD API calls.
    pattern = re.compile(r"\b(?:uetd|u[a-z][a-z0-9]*)_[A-Za-z][A-Za-z0-9_]*\s*\(")
    symbols = set()
    for header in headers:
        path = ROOT / Path(*PurePosixPath(header).parts)
        if not path.is_file():
            continue
        content = path.read_text(encoding="utf-8", errors="replace")
        symbols.update(match.group(0).split("(", 1)[0].strip() for match in pattern.finditer(content))
    return sorted(symbols)

def _render_template(
    module_id: str,
    manifest_path: str,
    record: dict[str, Any],
    sources: list[str],
    headers: list[str],
    future: bool,
    api_symbols: list[str],
) -> str:
    authoring = record.get("authoring")
    generation = authoring.get("generation", {}) if isinstance(authoring, dict) else {}
    authoring_status = authoring.get("status", "missing") if isinstance(authoring, dict) else "missing"
    generation_status = generation.get("status", "missing") if isinstance(generation, dict) else "missing"
    generation_paths = generation.get("template_paths", []) if isinstance(generation, dict) else []
    if not isinstance(generation_paths, list):
        generation_paths = []
    available = record.get("available_for_generation")
    if available is None and not record.get("scaffold_only", False):
        availability = "unspecified in module manifest"
    else:
        availability = str(bool(available))
    display_name = ""
    description = ""
    if isinstance(authoring, dict):
        display_name = _comment(authoring.get("display_name", ""))
        description = _comment(authoring.get("description", ""))
    stage = _comment(record.get("scaffold_stage", "future" if future else "catalog"))
    reason = _comment(record.get("scaffold_reason", ""))
    dependencies = record.get("dependencies", [])
    if not isinstance(dependencies, list):
        dependencies = []
    dependencies = [_comment(item) for item in dependencies]
    lines = [
        "/* " + GENERATED_MARKER,
        " * Non-renderable standalone module-route scope scaffold.",
        " * This file contains comments only. Do not add it to generation.template_paths.",
        " *",
        " * Module ID: " + module_id,
        " * Display name: " + (display_name or "(authoring display name not defined)"),
        " * Description: " + (description or "(authoring description not defined)"),
        " * Detail manifest: " + manifest_path,
        " * Catalog stage: " + stage,
        " * Future-scope path: " + str(future).lower(),
        " * available_for_generation: " + availability,
        " * authoring status: " + _comment(authoring_status),
        " * generation status: " + _comment(generation_status),
        " * existing standalone renderable template paths: " + (", ".join(_comment(item) for item in generation_paths) or "none"),
    ]
    if reason:
        lines.append(" * Scaffold reason: " + reason)
    lines.extend([" * Dependencies:"] + _comment_list(dependencies))
    lines.extend([" * Public headers from the module manifest:"] + _comment_list(headers))
    lines.extend([" * Implementation sources from the module manifest:"] + _comment_list(sources))
    lines.extend([" * Declared or discovered API operations:"] + _comment_list(api_symbols))
    lines.extend(
        [
            " *",
            " * TODO: decide whether this catalog item needs a generated component",
            " * binding at all, or is only a dependency/library source selection.",
            " * TODO: use the listed public headers and sources as the API/behavior",
            " * boundary; do not copy or reimplement their algorithm in the template.",
            " * TODO: define the standalone authoring inputs, typed values, ports,",
            " * lifecycle/operation calls, output files, and target/manual actions.",
            " * TODO: choose an allowlisted UETD generation route and add concrete",
            " * output template paths to the module manifest only after review.",
            " * TODO: keep unavailable/scaffold-only modules blocked until their C",
            " * contract, target support, dependencies, and generated behavior are ready.",
            " */",
            "",
        ]
    )
    return "\n".join(lines)

def _prune_stale(expected: set[Path]) -> None:
    if not OUTPUT_ROOT.exists():
        return
    for path in OUTPUT_ROOT.rglob("*.tmpl"):
        if path.resolve() in expected:
            continue
        try:
            contents = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if GENERATED_MARKER in contents:
            path.unlink()

def main() -> None:
    registry = _read_json(REGISTRY)
    modules = registry.get("modules")
    if not isinstance(modules, dict) or not modules:
        raise ValueError("registry/modules/registry.json must contain a non-empty modules object")
    if INDEX.exists():
        existing_index = _read_json(INDEX)
        if existing_index.get("generated_by") != GENERATOR_ID:
            raise ValueError(f"refusing to overwrite hand-maintained {INDEX.relative_to(ROOT)}")
    if CATALOG.exists() and GENERATED_MARKER not in CATALOG.read_text(encoding="utf-8"):
        raise ValueError(f"refusing to overwrite hand-maintained {CATALOG.relative_to(ROOT)}")
    records: dict[str, Any] = {}
    rendered: dict[Path, str] = {}
    expected: set[Path] = set()
    for module_id, module_ref in sorted(modules.items()):
        if not isinstance(module_ref, dict):
            raise ValueError(f"module registry entry {module_id!r} must be an object")
        manifest_path = _safe_relative(module_ref.get("manifest"), f"{module_id} manifest")
        manifest_file = ROOT / Path(*PurePosixPath(manifest_path).parts)
        if not manifest_file.is_file():
            raise FileNotFoundError(f"module manifest does not exist: {manifest_path}")
        record = _read_json(manifest_file)
        sources = _resource_paths(record, "sources")
        headers = _resource_paths(record, "headers")
        resources = sources + headers
        future = _is_future(module_id, record, resources)
        relative_template = _output_relative_path(module_id, future)
        template_path = OUTPUT_ROOT / relative_template
        if template_path in rendered:
            raise ValueError(f"multiple module IDs map to {relative_template.as_posix()}")
        symbols = _api_symbols(record, headers)
        content = _render_template(module_id, manifest_path, record, sources, headers, future, symbols)
        if template_path.exists():
            try:
                previous = template_path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError) as exc:
                raise ValueError(f"refusing to overwrite non-text template {relative_template}") from exc
            if GENERATED_MARKER not in previous:
                raise ValueError(f"refusing to overwrite hand-maintained {relative_template}")
        rendered[template_path] = content
        expected.add(template_path.resolve())
        missing = [resource for resource in resources if not _resource_exists(resource)]
        authoring = record.get("authoring")
        generation = authoring.get("generation", {}) if isinstance(authoring, dict) else {}
        template_paths = generation.get("template_paths", []) if isinstance(generation, dict) else []
        if not isinstance(template_paths, list):
            template_paths = []
        records[module_id] = {
            "template_scaffold": (Path("templates") / "modules" / relative_template).as_posix(),
            "detail_manifest": manifest_path,
            "sources": sources,
            "headers": headers,
            "api_symbols": symbols,
            "dependencies": record.get("dependencies", []),
            "future_scope": future,
            "scaffold_only": bool(record.get("scaffold_only", False)),
            "scaffold_stage": record.get("scaffold_stage"),
            "available_for_generation": record.get("available_for_generation"),
            "authoring_status": authoring.get("status") if isinstance(authoring, dict) else None,
            "generation_status": generation.get("status") if isinstance(generation, dict) else None,
            "standalone_renderable_template_paths": template_paths,
            "missing_resources": missing,
        }
    _prune_stale(expected)
    for path, content in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\r\n")
    index = {
        "schema_version": "1.0",
        "description": "Generated inventory of non-renderable standalone module-route template scaffolds.",
        "generated_by": GENERATOR_ID,
        "generated_marker": GENERATED_MARKER,
        "module_count": len(records),
        "future_scope_count": sum(1 for item in records.values() if item["future_scope"]),
        "renderable_template_paths_added": 0,
        "modules": records,
    }
    INDEX.parent.mkdir(parents=True, exist_ok=True)
    INDEX.write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\r\n")
    catalog_lines = [
        "<!-- " + GENERATED_MARKER + " -->",
        "# Module route scaffold index",
        "",
        f"Catalog entries: **{len(records)}**; future-scoped paths: **{index['future_scope_count']}**.",
        "These route files are non-renderable checklists; see `README.md` for status and use.",
        "",
        "| Module ID | Scope | Availability | Authoring | Headers | Sources | Route checklist |",
        "|---|---|---|---|---:|---:|---|",
    ]
    for module_id, item in records.items():
        scope = "future" if item["future_scope"] else "catalog"
        availability = item["available_for_generation"]
        if availability is None:
            availability = "unspecified"
        authoring_status = item["authoring_status"] or "missing"
        route = item["template_scaffold"].removeprefix("templates/modules/")
        catalog_lines.append(
            f"| `{module_id}` | {scope} | {str(availability).lower()} | {authoring_status} | "
            f"{len(item['headers'])} | {len(item['sources'])} | [`route.tmpl`]({route}) |"
        )
    CATALOG.write_text("\n".join(catalog_lines) + "\n", encoding="utf-8", newline="\r\n")
    print(f"Wrote {len(rendered)} module template-scope scaffolds to {OUTPUT_ROOT.relative_to(ROOT)}")
    print(f"Future-scoped templates: {index['future_scope_count']}")
    missing_count = sum(len(item["missing_resources"]) for item in records.values())
    print(f"Missing source/header references recorded: {missing_count}")


if __name__ == "__main__":
    main()
