def _operation_plan(key: str, entry: dict[str, Any]) -> list[dict[str, str]]:
    current = entry.get("scaffold_operations")
    if entry.get("scaffold_outline_version") == 5 and isinstance(current, list) and current:
        return current
    blueprints = KALMAN_DETAILED_OPERATIONS.get(key)
    if blueprints is None and entry.get("scaffold_outline_version") == 4 and isinstance(current, list) and current:
        operations = [dict(operation) for operation in current]
    else:
        if blueprints is None:
            blueprints = SPECIAL_OPERATIONS.get(key)
        family = str(entry.get("family", ""))
        if blueprints is None:
            candidates = [family, family.split("/")[0]]
            blueprints = next((OPERATION_PROFILES[item] for item in candidates if item in OPERATION_PROFILES), OPERATION_PROFILES["default"])
        description = _comment(entry.get("description", key))
        operations = []
        for name, purpose, task in blueprints:
            operations.append({
                "name": name,
                "purpose": purpose,
                "todo": task + " Algorithm-specific focus: " + description,
            })

    for operation in operations:
        todo = str(operation.get("todo", ""))
        if not todo.startswith("Implementation sequence:") and not re.match(r"^\d+\)", todo):
            purpose = str(operation.get("purpose", operation.get("name", "operation")))
            operation["todo"] = (
                "Implementation sequence: 1) Validate pointers, configuration, dimensions, and "
                "preconditions before writing outputs or state. 2) " + purpose + " 3) Check "
                "numeric results, declared constraints, and fixed work/memory bounds. 4) Commit "
                "outputs, state, and diagnostics together only after success; preserve prior "
                "values on failure. Operation-specific requirements: " + todo
            )
    entry["scaffold_outline_version"] = 5
    return operations


def _comment_lines(label: str, value: object, width: int = 94) -> list[str]:
    wrapped = textwrap.wrap(_comment(value), width=max(24, width - len(label)),
                            break_long_words=False, break_on_hyphens=False) or [""]
    continuation = "/// " if label.startswith("///") else " * "
    return [label + wrapped[0]] + [continuation + line for line in wrapped[1:]]


def _safe_parts(value: str, label: str) -> tuple[str, ...]:
    path = Path(value)
    if path.is_absolute() or ".." in path.parts or not path.parts:
        raise ValueError(f"unsafe {label}: {value!r}")
    return path.parts


def _family_parts(value: str) -> tuple[str, ...]:
    parts = _safe_parts(value, "UCON family path")
    if parts[0] not in FAMILY_ROOTS:
        raise ValueError(f"unknown UCON family category in {value!r}")
    # Public naming uses the category "estimators" for the specification's
    # singular family label "estimation" (for example estimators/kalman/ekf.h).
    if parts[0] == "estimation":
        return ("estimators", *parts[1:])
    return parts


def _algorithm_paths(key: str, entry: dict[str, Any]) -> tuple[str, str, str, str]:
    priority = entry.get("priority")
    stage = PRIORITY_STAGE.get(priority)
    if stage is None:
        raise ValueError(f"{key} has unsupported roadmap priority {priority!r}")
    if priority == "PLANNED" and key in INITIAL_PLANNED:
        stage = "initial"
    family = entry.get("family")
    if not isinstance(family, str) or not family:
        raise ValueError(f"{key} has no family path")
    family_parts = _family_parts(family)
    tree = () if stage == "initial" else ("future",)
    slug = key.lower()
    relative = Path(*tree, *family_parts, slug)
    header = (Path("include") / "uef" / "ucon" / relative).with_suffix(".h").as_posix()
    source = (Path("src") / "ucon" / relative).with_suffix(".c").as_posix()
    module = (Path("ucon") / relative).as_posix()
    return stage, header, source, module


def _template_scaffold_path(key: str, entry: dict[str, Any]) -> str:
    family = entry.get("family")
    if not isinstance(family, str) or not family:
        raise ValueError(f"{key} has no family path for its template scaffold")
    relative = Path(*_family_parts(family), key.lower() + ".h.tmpl")
    return (Path("templates") / "ucon" / "first_pass" / relative).as_posix()


def _stage_reason(key: str, entry: dict[str, Any]) -> tuple[str, list[str]]:
    priority = entry.get("priority")
    if priority == "FIRST_PASS":
        return "FIRST_PASS catalog priority; included in the initial scaffold wave.", ["first_pass"]
    if key in INITIAL_PLANNED:
        project, reason = INITIAL_PLANNED[key]
        return reason, [project]
    if priority == "DEFERRED":
        return "The catalog marks this algorithm DEFERRED; retained in the future backlog.", []
    return "The catalog marks this algorithm PLANNED but it is outside the current project/common set.", []


def _comment(value: object) -> str:
    """Keep catalog-provided text safe and readable inside generated comments."""
    return str(value).replace("*/", "* /").replace("\r", " ").replace("\n", " ").strip()


def _list_text(value: object) -> str:
    if not isinstance(value, list):
        return "none declared"
    return ", ".join(_comment(item) for item in value) or "none declared"


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\r\n")


def _render_common_header() -> str:
    return "\n".join([
        "/// " + GENERATED_MARKER,
        "/// Internal type-erased call envelope used only by unfinished UCON algorithms.",
        "/// Replace each use with an algorithm-specific configuration and fixed-size state contract.",
        "#ifndef UEF_UCON_DETAIL_ALGORITHM_CALL_H",
        "#define UEF_UCON_DETAIL_ALGORITHM_CALL_H",
        "#include <uef/ucon/ucon_status.h>",
        "#ifdef __cplusplus", 'extern "C" {', "#endif",
        "typedef struct {",
        "    const void *configuration; /* TODO: replace with a typed algorithm configuration. */",
        "    void *state;               /* TODO: replace with bounded, fixed-size algorithm state. */",
        "    const ucon_scalar_t *inputs;",
        "    size_t input_count;",
        "    ucon_scalar_t *outputs;",
        "    size_t output_count;",
        "} ucon_algorithm_scaffold_call_t;",
        "#ifdef __cplusplus", "}", "#endif",
        "#endif /* UEF_UCON_DETAIL_ALGORITHM_CALL_H */", "",
    ])


def _render_header(key: str, entry: dict[str, Any], relative_header: str) -> str:
    guard = "UEF_UCON_SCAFFOLD_" + re.sub(r"[^A-Za-z0-9]", "_", key).upper() + "_H"
    stage = str(entry["scaffold_stage"])
    operations = _operation_plan(key, entry)
    lines = [
        "/// " + GENERATED_MARKER,
        "/// @file " + relative_header,
        "/// @brief " + stage.title() + "-wave fail-closed module outline for " + key + ".",
        "#ifndef " + guard, "#define " + guard,
        "#include <uef/ucon/detail/algorithm_call.h>",
        "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
        "/// " + _comment(entry.get("description", "No algorithm summary is recorded.")),
        "/// Development outline only; this is not a typed or usable algorithm API.",
        "/// Roadmap priority: " + str(entry.get("priority")) + ".",
        "/// Every operation returns UCON_NOT_IMPLEMENTED until its contract is reviewed.", "",
    ]
    for operation in operations:
        function = "ucon_" + key.lower() + "_" + operation["name"]
        lines.extend(_comment_lines("/// ", operation["purpose"]))
        lines.extend(_comment_lines("/// TODO(" + key + "." + operation["name"] + "): ", operation["todo"]))
        lines.extend(["ucon_status_t " + function + "(const ucon_algorithm_scaffold_call_t *call);", ""])
    lines.extend(["#ifdef __cplusplus", "}", "#endif", "", "#endif /* " + guard + " */", ""])
    return "\n".join(lines)


def _render_source(key: str, entry: dict[str, Any], relative_source: str,
                   relative_header: str) -> str:
    operations = _operation_plan(key, entry)
    gaps = _list_text(entry.get("review_gaps", []))
    lines = [
        "/// " + GENERATED_MARKER,
        "/// @file " + relative_source,
        "/// @brief Fail-closed operation outline; no algorithm behavior is implemented.",
        "#include <uef/ucon/detail/algorithm_call.h>",
        "#include <" + relative_header.replace("include/", "", 1) + ">", "",
        "/**",
        " * Catalogue summary: " + _comment(entry.get("description", "No algorithm summary is recorded.")),
        " * Contract maturity: " + str(entry.get("contract_status", "catalogue_only")) + ".",
        " * Roadmap priority: " + str(entry.get("priority")) + ".",
        " * Declared features: " + _list_text(entry.get("features", [])) + ".",
        " * Declared numeric helpers: " + _list_text(entry.get("numerics", [])) + ".",
        " * Declared algorithm modules: " + _list_text(entry.get("modules", [])) + ".",
        " * Contract gaps: " + gaps + ".",
        " * Replace this shared type-erased envelope with typed fixed-size state/configuration.",
        " * Keep the entry unregistered until implementation, numeric limits, and templates are reviewed.",
        " */", "",
    ]
    for operation in operations:
        function = "ucon_" + key.lower() + "_" + operation["name"]
        lines.extend(_comment_lines("/* TODO(" + key + "." + operation["name"] + "): ", operation["todo"]))
        lines.extend([" * This stub must not read/write opaque state or output buffers.", " */",
                      "ucon_status_t " + function + "(const ucon_algorithm_scaffold_call_t *call)",
                      "{", "    if (call == NULL) {", "        return UCON_INVALID_ARGUMENT;",
                      "    }", "    return UCON_NOT_IMPLEMENTED;", "}", ""])
    return "\n".join(lines)


def _render_template_scaffold(key: str, entry: dict[str, Any],
                              relative_template: str) -> str:
    """Render an inert wrapper-template checklist until the algorithm has a typed API."""
    operations = _operation_plan(key, entry)
    lines = [
        "/* " + GENERATED_MARKER,
        " * @file " + relative_template,
        " * TODO-only ControlIR wrapper-template scaffold for " + key + ".",
        " * This file renders documentation comments only; it is not an algorithm implementation.",
        " *",
    ]
    wrapper_steps = [
        "Replace this checklist with an instance wrapper only after the algorithm has a reviewed typed, allocation-free configuration/state API and concrete init/reset/step contract.",
        "Map the selected ControlIR node's declared parameters, dimensions, units, sample timing, named ports, and status outputs to that API; reject undeclared fields rather than guessing defaults.",
        "Keep per-instance state independent, call the UEF implementation instead of duplicating the control/estimation equations, and preserve its validation, bounds, failure, and output-commit behavior.",
        "Declare the required UEF module, generated output path, accepted structural fields, and any manual actions in the algorithm manifest; keep registered/renderable false until direct and generated behavior are reviewed together.",
    ]
    for index, step in enumerate(wrapper_steps, 1):
        lines.extend(_comment_lines(" * " + str(index) + ") ", step))
    lines.extend([
        " *",
        " * Function-level implementation checklist from the algorithm scaffold:",
    ])
    for operation in operations:
        lines.extend(_comment_lines(
            " * TODO(" + key + "." + operation["name"] + "): ", operation["todo"]))
    lines.extend([" */", ""])
    return "\n".join(lines)


def _render_module_record(key: str, entry: dict[str, Any]) -> dict[str, Any]:
    operations = _operation_plan(key, entry)
    return {
        "sources": [entry["scaffold_source"]],
        "headers": [entry["scaffold_header"]],
        "dependencies": ["ucon/core"],
        "scaffold_only": True,
        "available_for_generation": False,
        "algorithm": key,
        "priority": entry["priority"],
        "scaffold_stage": entry["scaffold_stage"],
        "scaffold_reason": entry["scaffold_reason"],
        "contract_status": entry.get("contract_status", "catalogue_only"),
        "outlined_functions": ["ucon_" + key.lower() + "_" + op["name"] for op in operations],
        "project_relevance": entry["project_relevance"],
        "generated_by": GENERATOR_ID,
    }


def _refresh_module_manifest(algorithms: dict[str, dict[str, Any]]) -> None:
    document = load_module_registry(ROOT)
    modules = document.get("modules")
    if not isinstance(modules, dict):
        raise ValueError("registry/modules/registry.json must contain a modules object")

    old_grouped = {
        "ucon/scaffold/" + "/".join(_safe_parts(str(entry["family"]), "UCON family path"))
        for entry in algorithms.values()
        if entry.get("registered") is not True and isinstance(entry.get("family"), str)
    }
    for name, record in list(modules.items()):
        if (isinstance(record, dict) and record.get("generated_by") == GENERATOR_ID) or name in old_grouped:
            modules.pop(name)

    for key, entry in algorithms.items():
        if entry.get("registered") is True:
            continue
        modules[entry["scaffold_module"]] = _render_module_record(key, entry)
    write_module_registry(document, ROOT)


def _refresh_api_document() -> None:
    document = json.loads(API.read_text(encoding="utf-8"))
    ucon_api = document.get("ucon_api")
    if not isinstance(ucon_api, dict):
        raise ValueError("uef_api.json must contain a ucon_api object")
    ucon_api["scaffold_header"] = "uef/ucon/detail/algorithm_call.h"
    ucon_api["per_algorithm_operation_functions"] = True
    ucon_api["operation_todos_are_function_scoped"] = True
    ucon_api["scaffold_tree"] = {
        "initial_headers_root": "include/uef/ucon",
        "initial_sources_root": "src/ucon",
        "future_headers_root": "include/uef/ucon/future",
        "future_sources_root": "src/ucon/future",
        "one_algorithm_per_header_and_source": True,
        "first_pass_template_scaffold_root": "templates/ucon/first_pass",
        "first_pass_template_scaffolds_are_todo_only": True,
        "generator": "tools/generate_ucon_scaffolds.py",
        "future_policy": "Unselected PLANNED and all DEFERRED entries are repository-only and not selectable by uef-gen",
        "initial_planned_algorithms": sorted(INITIAL_PLANNED),
    }
    _write(API, json.dumps(document, indent=2, ensure_ascii=False) + "\n")


def _prune_generated_files(expected: set[Path]) -> None:
    roots = (INCLUDE_ROOT, SOURCE_ROOT, TEMPLATE_SCAFFOLD_ROOT)
    for root in roots:
        if not root.exists():
            continue
        for path in root.rglob("*"):
            if not path.is_file() or path.resolve() in expected:
                continue
            try:
                content = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            if GENERATED_MARKER in content:
                path.unlink()

    # Leave hand-maintained files/directories alone; remove only empty folders.
    for root in roots:
        if not root.exists():
            continue
        for path in sorted((item for item in root.rglob("*") if item.is_dir()),
                           key=lambda item: len(item.parts), reverse=True):
            try:
                path.rmdir()
            except OSError:
                pass


def main() -> None:
    manifest = load_control_ir_registry(ROOT)
    algorithms = manifest.get("algorithms")
    if not isinstance(algorithms, dict):
        raise ValueError("UEF manifest must contain an algorithms object")
    missing_selected = sorted(set(INITIAL_PLANNED) - set(algorithms))
    if missing_selected:
        raise ValueError("project-relevant UCON keys are missing from the catalog: " + ", ".join(missing_selected))
    incorrectly_prioritized = sorted(
        key for key in INITIAL_PLANNED if algorithms[key].get("priority") != "PLANNED"
    )
    if incorrectly_prioritized:
        raise ValueError("project-relevant overrides must reference PLANNED entries: " + ", ".join(incorrectly_prioritized))

    aliases = manifest.get("aliases", {})
    if not isinstance(aliases, dict):
        raise ValueError("UEF manifest aliases must be an object")
    for alias, target in aliases.items():
        if alias in algorithms:
            raise ValueError(f"alias {alias} also exists as a concrete algorithm key")
        targets = target if isinstance(target, list) else [target]
        if not targets or any(item not in algorithms for item in targets):
            raise ValueError(f"alias {alias} targets an unknown algorithm")

    functions: set[str] = set()
    expected_files: set[Path] = set()
    generated_count = 0
    for key, entry in algorithms.items():
        if not IDENTIFIER.fullmatch(key) or not isinstance(entry, dict):
            raise ValueError(f"invalid UCON catalogue entry: {key!r}")
        if entry.get("registered") is True:
            # A promoted algorithm's typed API is its canonical declaration;
            # discard stale placeholder paths/functions from its old scaffold.
            for field in (
                "scaffold_function", "scaffold_header", "scaffold_source",
                "scaffold_stage", "scaffold_module", "scaffold_reason",
                "scaffold_operations", "scaffold_outline_version", "scaffold_function",
                "scaffold_template", "project_relevance",
            ):
                entry.pop(field, None)
            continue
        operations = _operation_plan(key, entry)
        if not operations:
            raise ValueError(f"{key} has no scaffold operation outline")
        operation_names: set[str] = set()
        for operation in operations:
            if not isinstance(operation, dict):
                raise ValueError(f"{key} has a malformed scaffold operation")
            name = operation.get("name")
            if not isinstance(name, str) or not C_FUNCTION.fullmatch(name):
                raise ValueError(f"{key} has an invalid operation name: {name!r}")
            function = "ucon_" + key.lower() + "_" + name
            if name in operation_names or function in functions:
                raise ValueError(f"duplicate UCON scaffold function name: {function}")
            if not operation.get("purpose") or not operation.get("todo"):
                raise ValueError(f"{key}.{name} needs a purpose and function-specific TODO")
            operation_names.add(name)
            functions.add(function)

        stage, header, source, module = _algorithm_paths(key, entry)
        reason, project_relevance = _stage_reason(key, entry)
        entry["scaffold_stage"] = stage
        entry["scaffold_reason"] = reason
        entry["project_relevance"] = project_relevance
        entry["scaffold_operations"] = operations
        entry["scaffold_outline_version"] = 5
        entry.pop("scaffold_function", None)
        entry["scaffold_module"] = module
        entry["scaffold_header"] = header
        entry["scaffold_source"] = source
        header_path = ROOT / header
        source_path = ROOT / source
        _write(header_path, _render_header(key, entry, header))
        _write(source_path, _render_source(key, entry, source, header))
        expected_files.update((header_path.resolve(), source_path.resolve()))
        if entry.get("priority") == "FIRST_PASS":
            template = _template_scaffold_path(key, entry)
            template_path = ROOT / template
            entry["scaffold_template"] = template
            _write(template_path, _render_template_scaffold(key, entry, template))
            expected_files.add(template_path.resolve())
        else:
            entry.pop("scaffold_template", None)
        generated_count += 1

    common = INCLUDE_ROOT / "detail" / "algorithm_call.h"
    _write(common, _render_common_header())
    expected_files.add(common.resolve())
    manifest["algorithms"] = algorithms
    write_control_ir_registry(manifest, ROOT)
    _refresh_module_manifest(algorithms)
    _refresh_api_document()
    _prune_generated_files(expected_files)
    print(f"Generated {generated_count} individual UCON algorithm scaffold pairs.")


if __name__ == "__main__":
    main()
